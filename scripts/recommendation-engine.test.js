// 7-11: generateRecommendations produces exactly the expected triggered rules, with correctly-derived
//       reason/size/risk/affectedFiles per rule, and skips undetected modules and modules with no
//       triggered rule entirely.
{
  const dir = makeFixture();
  const mod = requireFixture(dir);
  const recs = mod.generateRecommendations(KNOWLEDGE_FIXTURE);
  const byRule = (moduleName, ruleKey) => recs.find((rec) => rec.affectedModules[0] === moduleName && rec.ruleKey === ruleKey);

  // 7. extract-complex-logic: triggers for Authentication (High complexity + Medium risk), not for
  //    Attendance (Low complexity) or Reports (Medium complexity, not High).
  const authExtract = byRule("Authentication", "extract-complex-logic");
  if (!authExtract) throw new Error("expected extract-complex-logic to trigger for Authentication");
  if (authExtract.estimatedRisk !== "Low") throw new Error(`expected Medium module risk to map to Low implementation risk, got ${authExtract.estimatedRisk}`);
  if (authExtract.estimatedImplementationSize !== "Small") throw new Error(`expected extract-complex-logic size Small, got ${authExtract.estimatedImplementationSize}`);
  if (JSON.stringify(authExtract.reason) !== JSON.stringify(["Authentication has High complexity", "Medium maintenance risk", "Touches 3 related file(s)"])) {
    throw new Error(`unexpected reason array: ${JSON.stringify(authExtract.reason)}`);
  }
  if (byRule("Attendance", "extract-complex-logic") || byRule("Reports", "extract-complex-logic")) {
    throw new Error("expected extract-complex-logic to NOT trigger for Attendance or Reports (complexity not High)");
  }

  // 8. reduce-coupling: triggers for Authentication (High importance + 2 coupled modules), with
  //    affectedFiles being the true file-level intersection with Attendance only (Reports shares nothing).
  const authCoupling = byRule("Authentication", "reduce-coupling");
  if (!authCoupling) throw new Error("expected reduce-coupling to trigger for Authentication");
  if (JSON.stringify(authCoupling.affectedFiles) !== JSON.stringify(["backend/routes/attendanceRoutes.js"])) {
    throw new Error(`expected reduce-coupling affectedFiles to be exactly the true file intersection, got: ${JSON.stringify(authCoupling.affectedFiles)}`);
  }
  if (JSON.stringify(authCoupling.affectedModules) !== JSON.stringify(["Authentication", "Attendance", "Reports"])) {
    throw new Error(`expected reduce-coupling affectedModules to include the module plus its coupled modules, got: ${JSON.stringify(authCoupling.affectedModules)}`);
  }
  if (byRule("Attendance", "reduce-coupling") || byRule("Reports", "reduce-coupling")) {
    throw new Error("expected reduce-coupling to NOT trigger for Attendance (Medium importance) or Reports (0 coupled modules)");
  }

  // 9. address-maintenance-risk: triggers only for Attendance (High risk).
  if (!byRule("Attendance", "address-maintenance-risk")) throw new Error("expected address-maintenance-risk to trigger for Attendance");
  if (byRule("Authentication", "address-maintenance-risk") || byRule("Reports", "address-maintenance-risk")) {
    throw new Error("expected address-maintenance-risk to NOT trigger for Authentication (Medium risk) or Reports (Low risk)");
  }

  // 10. strengthen-detection-coverage: triggers for Reports (weak + Medium criticality), NOT for Attendance
  //     (weak but Low criticality -- the negative case for the criticality gate).
  if (!byRule("Reports", "strengthen-detection-coverage")) throw new Error("expected strengthen-detection-coverage to trigger for Reports");
  if (byRule("Attendance", "strengthen-detection-coverage")) {
    throw new Error("expected strengthen-detection-coverage to NOT trigger for Attendance (weak confidence but Low criticality)");
  }

  // 11. Faculty (all-Low, strong confidence) triggers nothing; Admin (undetected) is skipped entirely
  //     regardless of any field values.
  if (recs.some((rec) => rec.affectedModules.includes("Faculty"))) throw new Error("expected Faculty to trigger no recommendations at all");
  if (recs.some((rec) => rec.affectedModules.includes("Admin"))) throw new Error("expected undetected Admin to be skipped entirely");

  ok("generateRecommendations triggers exactly the expected rules with correctly-derived fields, including all documented negative cases");
}

// 12. buildRecommendationsReport sorts by descending priority (confidence as tiebreak), preserves stable
//     ids independent of the sort, and includes the documented metadata fields.
{
  const dir = makeFixture();
  const mod = requireFixture(dir);
  const report = mod.buildRecommendationsReport(KNOWLEDGE_FIXTURE);
  for (const key of ["generatedFrom", "sourceProjectName", "sourceTimestamp", "scoringFormula", "recommendations", "timestamp"]) {
    if (!(key in report)) throw new Error(`report is missing required field: ${key}`);
  }
  const scores = report.recommendations.map((rec) => rec.priorityScore);
  const sortedDescending = [...scores].sort((a, b) => b - a);
  if (JSON.stringify(scores) !== JSON.stringify(sortedDescending)) throw new Error(`expected recommendations sorted by descending priorityScore, got: ${JSON.stringify(scores)}`);
  // Authentication's two recommendations share priorityScore 88; among ties, higher confidence must sort first.
  const authRecs = report.recommendations.filter((rec) => rec.affectedModules[0] === "Authentication");
  if (authRecs.length === 2 && authRecs[0].confidence < authRecs[1].confidence) {
    throw new Error(`expected the tied-priority Authentication recommendations to be ordered by descending confidence, got: ${JSON.stringify(authRecs.map((r) => r.confidence))}`);
  }
  const ids = report.recommendations.map((rec) => rec.id);
  if (new Set(ids).size !== ids.length) throw new Error("expected every recommendation id to be unique");
  ok("buildRecommendationsReport sorts by descending priority with a confidence tiebreak and includes all documented metadata");
}

// 13. renderMarkdown includes the expected sections, and reports the empty-recommendations case honestly.
{
  const dir = makeFixture();
  const mod = requireFixture(dir);
  const report = mod.buildRecommendationsReport(KNOWLEDGE_FIXTURE);
  const markdown = mod.renderMarkdown(report);
  for (const heading of ["# Engineering Recommendations Report", "## Scoring formula", "## Recommendations", "**Priority score:**", "**Reason:**", "**Affected files:**"]) {
    if (!markdown.includes(heading)) throw new Error(`expected markdown to include "${heading}"`);
  }

  const emptyKnowledge = { ...KNOWLEDGE_FIXTURE, modules: [KNOWLEDGE_FIXTURE.modules[3]] }; // only Faculty (triggers nothing)
  const emptyReport = mod.buildRecommendationsReport(emptyKnowledge);
  if (emptyReport.recommendations.length !== 0) throw new Error("expected a module that triggers nothing to produce zero recommendations");
  const emptyMarkdown = mod.renderMarkdown(emptyReport);
  if (!/No recommendations were triggered/.test(emptyMarkdown)) throw new Error("expected the empty case to be reported honestly in markdown, not silently omitted");
  ok("renderMarkdown includes the expected sections and honestly reports the empty-recommendations case");
}

// 14. writeOutputs persists both files, and ENGINEERING_KNOWLEDGE_PATH / RECOMMENDATIONS_OUTPUT_DIR
//     override the default input/output locations.
{
  const dir = makeFixture();
  const customInput = path.join(dir, "custom-input/knowledge.json");
  writeJson(customInput, KNOWLEDGE_FIXTURE);
  const previousInput = process.env.ENGINEERING_KNOWLEDGE_PATH;
  const previousOutput = process.env.RECOMMENDATIONS_OUTPUT_DIR;
  process.env.ENGINEERING_KNOWLEDGE_PATH = "custom-input/knowledge.json";
  process.env.RECOMMENDATIONS_OUTPUT_DIR = "custom-output/nested";
  try {
    const mod = requireFixture(dir);
    if (mod.inputPath !== customInput) throw new Error(`expected overridden input path, got: ${mod.inputPath}`);
    if (mod.outputDir !== path.join(dir, "custom-output", "nested")) throw new Error(`expected overridden output directory, got: ${mod.outputDir}`);
    const report = mod.buildRecommendationsReport(mod.loadEngineeringKnowledge(mod.inputPath));
    const { jsonPath, mdPath } = mod.writeOutputs(report);
    if (path.basename(jsonPath) !== "recommendations.json") throw new Error(`expected output named recommendations.json, got ${jsonPath}`);
    if (path.basename(mdPath) !== "recommendations.md") throw new Error(`expected output named recommendations.md, got ${mdPath}`);
    if (!fs.existsSync(jsonPath) || !fs.existsSync(mdPath)) throw new Error("expected both output files to exist under the overridden output directory");
    JSON.parse(fs.readFileSync(jsonPath, "utf8"));
  } finally {
    if (previousInput === undefined) delete process.env.ENGINEERING_KNOWLEDGE_PATH; else process.env.ENGINEERING_KNOWLEDGE_PATH = previousInput;
    if (previousOutput === undefined) delete process.env.RECOMMENDATIONS_OUTPUT_DIR; else process.env.RECOMMENDATIONS_OUTPUT_DIR = previousOutput;
  }
  ok("ENGINEERING_KNOWLEDGE_PATH and RECOMMENDATIONS_OUTPUT_DIR override the default input/output locations");
}

