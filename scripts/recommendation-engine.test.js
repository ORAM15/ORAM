{
  const dir = makeFixture();
  const result = spawnSync("node", ["scripts/recommendation-engine.js"], { cwd: dir, encoding: "utf8" });
  if (result.status === 0) throw new Error(`expected the CLI to fail closed with no engineering-knowledge.json present:\n${result.stdout}`);
  if (!/engineering-knowledge\.json not found/.test(result.stderr)) throw new Error(`expected a clear missing-input error on stderr, got:\n${result.stderr}`);
  ok("CLI fails closed with a clear error when engineering-knowledge.json has not been generated yet");
}

// 16. True end-to-end: the real three-stage chain (repository-intelligence.js -> engineering-knowledge.js
//     -> recommendation-engine.js), using the real upstream sources, produces valid recommendations output.
{
  const dir = makeFixture(true);
  const repoIntelRun = spawnSync("node", ["scripts/repository-intelligence.js"], { cwd: dir, encoding: "utf8" });
  if (repoIntelRun.status !== 0) throw new Error(`Repository Intelligence run failed:\n${repoIntelRun.stdout}\n${repoIntelRun.stderr}`);
  const knowledgeRun = spawnSync("node", ["scripts/engineering-knowledge.js"], { cwd: dir, encoding: "utf8" });
  if (knowledgeRun.status !== 0) throw new Error(`Engineering Knowledge run failed:\n${knowledgeRun.stdout}\n${knowledgeRun.stderr}`);
  const run = spawnSync("node", ["scripts/recommendation-engine.js"], { cwd: dir, encoding: "utf8" });
  if (run.status !== 0) throw new Error(`Recommendation Engine run failed:\n${run.stdout}\n${run.stderr}`);
  const jsonPath = path.join(dir, "recommendations", "recommendations.json");
  const mdPath = path.join(dir, "recommendations", "recommendations.md");
  if (!fs.existsSync(jsonPath)) throw new Error("expected recommendations.json to be produced by the real end-to-end chain");
  if (!fs.existsSync(mdPath)) throw new Error("expected recommendations.md to be produced by the real end-to-end chain");
  const report = JSON.parse(fs.readFileSync(jsonPath, "utf8"));
  if (!Array.isArray(report.recommendations)) throw new Error("expected the real end-to-end run to produce a recommendations array");
  ok("the real three-stage chain (repository-intelligence.js -> engineering-knowledge.js -> recommendation-engine.js) produces valid output");
}

console.log("All Recommendation Engine v1 regression scenarios passed.");
